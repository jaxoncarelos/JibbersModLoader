//! Game-build identification and the compatibility list.
//!
//! The mods hook obfuscated game classes and fields. A game update can move or rename them, and a
//! hook on the wrong code crashes natively (inside `UnityPlayer.dll`), where no `catch_unwind`
//! helps. So before anything is hooked, the loader fingerprints the running game and compares it
//! with the builds the mods were *validated* on. This module is that logic, shared (by path) by the
//! loader (`version.dll`) and the SDK runtime so both give the same verdict.
//!
//! **Fingerprint** = `GameAssembly.dll` file size + a hash of its PE headers (which hold the link
//! timestamp, image size and the section table, so any rebuild changes it) + Unity's product
//! version (`6000.3.12f1 (fca03ac9b0d5)`, from `UnityPlayer.dll`'s version resource). All three
//! must match a known build. Reading it touches no IL2CPP and runs no game code.
//!
//! **Compatibility list** = `compat.json`. One copy is compiled into the loader and the runtime;
//! the SDK auto-updater installs a newer one as `JibbersMods\sdk\compat.json`. The newer
//! `sdkVersion` wins. The file is generated by `sdk-publish validate-build` and signed with the rest
//! of the release, so a game update is handled by publishing a release, not by reinstalling the
//! loader. A build enters the list only when the maintainer has tested the mods on it.
//!
//! `JIBBERS_HOTLOAD_FORCE=1` overrides the verdict (developer testing after a game update).

use serde_json::{json, Value};
use std::path::{Path, PathBuf};

pub const SCHEMA: u32 = 1;
/// Environment variable that forces mods to load on a build that is not in the list.
pub const FORCE_ENV: &str = "JIBBERS_HOTLOAD_FORCE";
/// Largest `compat.json` accepted from disk.
const MAX_LIST_BYTES: u64 = 256 * 1024;
/// How much of `GameAssembly.dll` is read to fingerprint it.
const HEADER_READ: usize = 4096;

/// What identifies one game build.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Fingerprint {
    /// Size of `GameAssembly.dll` on disk.
    pub assembly_size: u64,
    /// PE link timestamp of `GameAssembly.dll` (informational; also inside `header_hash`).
    pub pe_timestamp: u32,
    /// FNV-1a 64 of the PE headers (DOS header up to `SizeOfHeaders`).
    pub header_hash: u64,
    /// `UnityPlayer.dll` product version, e.g. `6000.3.12f1 (fca03ac9b0d5)`.
    pub unity: String,
}

impl Fingerprint {
    /// One line for logs.
    pub fn describe(&self) -> String {
        format!("GameAssembly {} bytes, header {:016x}, Unity {}", self.assembly_size, self.header_hash, self.unity)
    }
}

/// A build the mods were validated on: a [`Fingerprint`] plus who/when.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KnownBuild {
    pub label: String,
    pub fingerprint: Fingerprint,
    /// Date (YYYY-MM-DD) the maintainer validated it.
    pub validated: String,
    pub note: String,
}

impl KnownBuild {
    pub fn matches(&self, fp: &Fingerprint) -> bool {
        self.fingerprint.assembly_size == fp.assembly_size && self.fingerprint.header_hash == fp.header_hash && self.fingerprint.unity == fp.unity
    }

    pub fn to_json(&self) -> Value {
        json!({
            "label": self.label,
            "assemblySize": self.fingerprint.assembly_size,
            "peTimestamp": self.fingerprint.pe_timestamp,
            "headerHash": format!("{:016x}", self.fingerprint.header_hash),
            "unity": self.fingerprint.unity,
            "validated": self.validated,
            "note": self.note,
        })
    }

    fn from_json(v: &Value) -> Result<KnownBuild, String> {
        let text = |k: &str| v.get(k).and_then(Value::as_str).map(str::to_string);
        let label = text("label").ok_or("a build has no label")?;
        let err = |what: &str| format!("build {label:?}: {what}");
        let hash = text("headerHash").ok_or_else(|| err("no headerHash"))?;
        Ok(KnownBuild {
            fingerprint: Fingerprint {
                assembly_size: v.get("assemblySize").and_then(Value::as_u64).filter(|n| *n > 0).ok_or_else(|| err("bad assemblySize"))?,
                pe_timestamp: v.get("peTimestamp").and_then(Value::as_u64).unwrap_or(0) as u32,
                header_hash: u64::from_str_radix(&hash, 16).map_err(|_| err("headerHash must be 16 hex digits"))?,
                unity: text("unity").filter(|u| !u.is_empty()).ok_or_else(|| err("no unity version"))?,
            },
            validated: text("validated").unwrap_or_default(),
            note: text("note").unwrap_or_default(),
            label,
        })
    }
}

/// The set of validated builds, with the SDK release that generated it.
#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct CompatList {
    pub sdk_version: String,
    pub generated: String,
    pub builds: Vec<KnownBuild>,
}

pub fn parse_version(v: &str) -> Option<(u32, u32, u32)> {
    let mut it = v.split('.').map(|p| p.parse::<u32>().ok());
    let r = (it.next()??, it.next()??, it.next()??);
    it.next().is_none().then_some(r)
}

impl CompatList {
    pub fn parse(text: &str) -> Result<CompatList, String> {
        let v: Value = serde_json::from_str(text).map_err(|e| format!("not valid JSON: {e}"))?;
        if v.get("schema").and_then(Value::as_u64) != Some(SCHEMA as u64) {
            return Err(format!("unsupported schema (this build reads schema {SCHEMA})"));
        }
        let sdk_version = v.get("sdkVersion").and_then(Value::as_str).unwrap_or_default().to_string();
        parse_version(&sdk_version).ok_or("sdkVersion must be major.minor.patch")?;
        let builds = v.get("builds").and_then(Value::as_array).ok_or("no builds array")?.iter().map(KnownBuild::from_json).collect::<Result<Vec<_>, _>>()?;
        Ok(CompatList { sdk_version, generated: v.get("generated").and_then(Value::as_str).unwrap_or_default().to_string(), builds })
    }

    pub fn to_json(&self) -> Value {
        json!({"schema": SCHEMA, "sdkVersion": self.sdk_version, "generated": self.generated, "builds": self.builds.iter().map(KnownBuild::to_json).collect::<Vec<_>>()})
    }

    /// Adds `build`, or replaces the entry with the same fingerprint.
    pub fn upsert(&mut self, build: KnownBuild) {
        match self.builds.iter_mut().find(|b| b.matches(&build.fingerprint)) {
            Some(slot) => *slot = build,
            None => self.builds.push(build),
        }
    }

    pub fn find(&self, fp: &Fingerprint) -> Option<&KnownBuild> {
        self.builds.iter().find(|b| b.matches(fp))
    }

    /// The label of the newest build: what "the loader is built for".
    pub fn built_for(&self) -> String {
        self.builds.last().map(|b| b.label.clone()).unwrap_or_else(|| "no validated build".into())
    }

    fn version(&self) -> (u32, u32, u32) {
        parse_version(&self.sdk_version).unwrap_or((0, 0, 0))
    }
}

/// `<mods dir>\sdk\compat.json`, installed by the SDK updater.
pub fn installed_list_path(mods_dir: &Path) -> PathBuf {
    mods_dir.join("sdk").join("compat.json")
}

/// The list in force: the one compiled in (`embedded`), unless the updater installed one from a
/// newer SDK release. Returns the list and any problems worth logging (a bad file is ignored, a
/// broken embedded list leaves no builds, which blocks everything).
pub fn resolve_list(embedded: &str, mods_dir: &Path) -> (CompatList, Vec<String>) {
    let mut notes = vec![];
    let base = CompatList::parse(embedded).unwrap_or_else(|e| {
        notes.push(format!("built-in compatibility list is unusable: {e}"));
        CompatList::default()
    });
    let path = installed_list_path(mods_dir);
    let installed = match std::fs::metadata(&path) {
        Err(_) => None,
        Ok(m) if m.len() > MAX_LIST_BYTES => {
            notes.push(format!("{} is too large; ignored", path.display()));
            None
        }
        Ok(_) => match std::fs::read_to_string(&path).map_err(|e| e.to_string()).and_then(|t| CompatList::parse(&t)) {
            Ok(l) => Some(l),
            Err(e) => {
                notes.push(format!("{}: {e}; ignored", path.display()));
                None
            }
        },
    };
    match installed {
        Some(l) if l.version() >= base.version() => (l, notes),
        _ => (base, notes),
    }
}

/// Outcome of comparing the running game with the list.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Verdict {
    /// The build is in the list.
    Validated { label: String },
    /// Not in the list, and not overridden: mods stay off.
    Unvalidated { current: String, built_for: String },
    /// The game could not be identified: mods stay off (fail closed).
    Unidentified { why: String, built_for: String },
    /// Not validated, but `JIBBERS_HOTLOAD_FORCE` is set: mods load at the developer's risk.
    Forced { current: String, built_for: String },
}

impl Verdict {
    pub fn allows_mods(&self) -> bool {
        matches!(self, Verdict::Validated { .. } | Verdict::Forced { .. })
    }

    /// The single log line for this verdict.
    pub fn message(&self) -> String {
        match self {
            Verdict::Validated { label } => format!("game build validated: {label}"),
            Verdict::Unvalidated { current, built_for } => format!("game build {current} not validated; mods disabled (loader built for {built_for}). Set {FORCE_ENV}=1 to load anyway when testing"),
            Verdict::Unidentified { why, built_for } => format!("game build could not be identified ({why}); mods disabled (loader built for {built_for}). Set {FORCE_ENV}=1 to load anyway when testing"),
            Verdict::Forced { current, built_for } => format!("game build {current} not validated; loading mods anyway because {FORCE_ENV} is set (loader built for {built_for})"),
        }
    }
}

/// True for `JIBBERS_HOTLOAD_FORCE=1` (any value except empty or `0`).
pub fn force_requested(value: Option<&str>) -> bool {
    value.is_some_and(|v| !v.is_empty() && v != "0")
}

/// Decides, from a fingerprint (or why it could not be read) and a list.
pub fn evaluate(fp: &Result<Fingerprint, String>, list: &CompatList, force: bool) -> Verdict {
    let built_for = list.built_for();
    match fp {
        Ok(fp) => match list.find(fp) {
            Some(b) => Verdict::Validated { label: b.label.clone() },
            None if force => Verdict::Forced { current: fp.describe(), built_for },
            None => Verdict::Unvalidated { current: fp.describe(), built_for },
        },
        Err(_) if force => Verdict::Forced { current: "unidentified".into(), built_for },
        Err(why) => Verdict::Unidentified { why: why.clone(), built_for },
    }
}

/// [`resolve_list`] + [`evaluate`], reading the force flag from the environment.
pub fn assess(embedded: &str, mods_dir: &Path, fp: &Result<Fingerprint, String>) -> (Verdict, Vec<String>) {
    let (list, notes) = resolve_list(embedded, mods_dir);
    let force = force_requested(std::env::var(FORCE_ENV).ok().as_deref());
    (evaluate(fp, &list, force), notes)
}

fn fnv1a64(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325, |h, b| (h ^ *b as u64).wrapping_mul(0x0000_0100_0000_01b3))
}

fn u16_at(b: &[u8], at: usize) -> Option<u16> {
    Some(u16::from_le_bytes(b.get(at..at + 2)?.try_into().ok()?))
}

fn u32_at(b: &[u8], at: usize) -> Option<u32> {
    Some(u32::from_le_bytes(b.get(at..at + 4)?.try_into().ok()?))
}

/// `(link timestamp, hash of the headers)` from the first bytes of a PE32+ x64 file.
pub fn pe_header_summary(bytes: &[u8]) -> Result<(u32, u64), String> {
    let bad = || "GameAssembly.dll is not a 64-bit PE file".to_string();
    if bytes.get(..2) != Some(b"MZ") {
        return Err(bad());
    }
    let pe = u32_at(bytes, 0x3c).ok_or_else(bad)? as usize;
    if bytes.get(pe..pe + 4) != Some(b"PE\0\0") || u16_at(bytes, pe + 4) != Some(0x8664) {
        return Err(bad());
    }
    let optional = pe + 24;
    if u16_at(bytes, optional) != Some(0x20b) {
        return Err(bad());
    }
    let timestamp = u32_at(bytes, pe + 8).ok_or_else(bad)?;
    let headers = u32_at(bytes, optional + 60).ok_or_else(bad)? as usize;
    let covered = bytes.get(..headers).ok_or("PE headers are larger than the part read")?;
    Ok((timestamp, fnv1a64(covered)))
}

/// Unity's product version out of a `VS_VERSIONINFO` resource: the `ProductVersion` string
/// (`6000.3.12f1 (fca03ac9b0d5)`, which names the exact editor revision), else the numeric file
/// version (whose last part Windows truncates to 16 bits).
pub fn version_from_resource(blob: &[u8]) -> Option<String> {
    let key: Vec<u8> = "ProductVersion".encode_utf16().flat_map(u16::to_le_bytes).collect();
    let mut at = 0;
    while at + key.len() <= blob.len() {
        if blob[at..at + key.len()] == key[..] {
            let mut i = at + key.len();
            while u16_at(blob, i) == Some(0) {
                i += 2; // terminator and alignment padding
            }
            let mut units = vec![];
            while let Some(u) = u16_at(blob, i).filter(|u| *u != 0) {
                units.push(u);
                i += 2;
            }
            let s = String::from_utf16_lossy(&units);
            if !s.trim().is_empty() {
                return Some(s.trim().to_string());
            }
        }
        at += 2;
    }
    let mut at = 0;
    while at + 16 <= blob.len() {
        if u32_at(blob, at) == Some(0xFEEF_04BD) {
            let (ms, ls) = (u32_at(blob, at + 8)?, u32_at(blob, at + 12)?);
            return Some(format!("{}.{}.{}.{}", ms >> 16, ms & 0xffff, ls >> 16, ls & 0xffff));
        }
        at += 4;
    }
    None
}

#[cfg(windows)]
mod win {
    use super::*;
    use std::ffi::c_void;
    use windows_sys::Win32::Foundation::FreeLibrary;
    use windows_sys::Win32::System::LibraryLoader::{FindResourceW, GetModuleFileNameW, GetModuleHandleW, LoadLibraryExW, LoadResource, LockResource, SizeofResource, LOAD_LIBRARY_AS_DATAFILE};

    fn wide(s: &str) -> Vec<u16> {
        s.encode_utf16().chain(Some(0)).collect()
    }

    /// The version resource of a loaded module (a running DLL or one loaded as data).
    unsafe fn module_version(module: *mut c_void) -> Result<String, String> {
        // RT_VERSION = 16, resource id 1: MAKEINTRESOURCE values.
        let res = FindResourceW(module, 1 as *const u16, 16 as *const u16);
        if res.is_null() {
            return Err("UnityPlayer.dll has no version resource".into());
        }
        let size = SizeofResource(module, res) as usize;
        let data = LockResource(LoadResource(module, res)) as *const u8;
        if data.is_null() || size == 0 {
            return Err("UnityPlayer.dll version resource is unreadable".into());
        }
        version_from_resource(std::slice::from_raw_parts(data, size)).ok_or_else(|| "UnityPlayer.dll version resource has no version".to_string())
    }

    fn assembly_part(path: &Path) -> Result<(u64, u32, u64), String> {
        use std::io::Read;
        let mut f = std::fs::File::open(path).map_err(|e| format!("{}: {e}", path.display()))?;
        let size = f.metadata().map_err(|e| e.to_string())?.len();
        let mut head = vec![0u8; HEADER_READ.min(size as usize)];
        f.read_exact(&mut head).map_err(|e| format!("{}: {e}", path.display()))?;
        let (timestamp, hash) = pe_header_summary(&head)?;
        Ok((size, timestamp, hash))
    }

    /// Fingerprint of the game this process is running (needs GameAssembly.dll and UnityPlayer.dll loaded).
    pub fn fingerprint_loaded() -> Result<Fingerprint, String> {
        unsafe {
            let ga = GetModuleHandleW(wide("GameAssembly.dll").as_ptr());
            let unity = GetModuleHandleW(wide("UnityPlayer.dll").as_ptr());
            if ga.is_null() || unity.is_null() {
                return Err("GameAssembly.dll / UnityPlayer.dll are not loaded".into());
            }
            let mut buf = [0u16; 1024];
            let n = GetModuleFileNameW(ga, buf.as_mut_ptr(), buf.len() as u32) as usize;
            if n == 0 || n >= buf.len() {
                return Err("cannot locate GameAssembly.dll".into());
            }
            let (assembly_size, pe_timestamp, header_hash) = assembly_part(Path::new(&String::from_utf16_lossy(&buf[..n])))?;
            Ok(Fingerprint { assembly_size, pe_timestamp, header_hash, unity: module_version(unity)? })
        }
    }

    /// Fingerprint of a game folder, offline: reads the two DLLs, runs nothing (UnityPlayer.dll is
    /// mapped as data only).
    pub fn fingerprint_dir(dir: &Path) -> Result<Fingerprint, String> {
        let (assembly_size, pe_timestamp, header_hash) = assembly_part(&dir.join("GameAssembly.dll"))?;
        let unity_path = dir.join("UnityPlayer.dll");
        unsafe {
            let module = LoadLibraryExW(wide(&unity_path.to_string_lossy()).as_ptr(), std::ptr::null_mut(), LOAD_LIBRARY_AS_DATAFILE);
            if module.is_null() {
                return Err(format!("cannot open {}", unity_path.display()));
            }
            let unity = module_version(module);
            FreeLibrary(module);
            Ok(Fingerprint { assembly_size, pe_timestamp, header_hash, unity: unity? })
        }
    }
}

