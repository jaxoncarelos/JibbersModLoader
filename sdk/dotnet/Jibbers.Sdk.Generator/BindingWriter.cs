using System.Text;
using Jibbers.Sdk.Symbols;

namespace Jibbers.Sdk.Generator;

/// <summary>Writes the C# bindings: friendly (catalogue symbols) and raw (every class).</summary>
internal sealed class BindingWriter(Model m)
{
    const string Sym = "global::Jibbers.Sdk.Symbols";

    /// <summary>Member names of one generated type: properties are unique; methods may overload by C# signature.</summary>
    sealed class Members
    {
        readonly HashSet<string> props = new();
        readonly Dictionary<string, HashSet<string>> methods = new();

        public Members(string typeName)
        {
            props.Add(typeName);
            // Members every struct already has (System.Object / ValueType).
            foreach (var n in new[] { "ToString", "Equals", "GetHashCode", "GetType", "Finalize", "MemberwiseClone", "ReferenceEquals" })
            {
                props.Add(n);
            }
        }

        public string Take(string name, string? signature = null)
        {
            var n = name;
            if (signature is null)
            {
                while (props.Contains(n) || methods.ContainsKey(n))
                {
                    n += "_";
                }
                props.Add(n);
                return n;
            }
            while (props.Contains(n) || (methods.TryGetValue(n, out var sigs) && sigs.Contains(signature)))
            {
                n += "_";
            }
            if (!methods.TryGetValue(n, out var set))
            {
                methods[n] = set = new HashSet<string>();
            }
            set.Add(signature);
            return n;
        }
    }

    static string Header(string what) =>
        $"// <auto-generated>\n// {what}\n// Generated by jibbers-gen from symbols.json and a game dump. Do not edit.\n// </auto-generated>\n#nullable enable\n#pragma warning disable CS0108, CS0109, CS1573, CS1591, CS8981\n";

    public Dictionary<string, string> Write()
    {
        var files = new Dictionary<string, string>
        {
            ["Game.g.cs"] = Friendly(),
        };
        foreach (var g in m.RawClasses.GroupBy(r => r.Info.Image))
        {
            files[$"Interop.{Names.Ident(Path.GetFileNameWithoutExtension(g.Key))}.g.cs"] = Raw(g.Key, g.ToList());
        }
        return files;
    }

    // ---------------------------------------------------------------------------------------------
    // Shared member emitters.

    /// <summary>An instance or static field as a property. <paramref name="refExpr"/> names the field reference.</summary>
    void Field(StringBuilder o, string indent, string name, string refExpr, CsType t, bool isStatic, string doc)
    {
        var self = isStatic ? "0" : "Ptr";
        var st = isStatic ? "static " : "";
        void Doc() => o.Append($"{indent}/// <summary>{Names.Xml(doc)}</summary>\n");
        switch (t.Kind)
        {
            case Kind.Value:
                Doc();
                o.Append($"{indent}public {st}{t.Cs} {name} {{ get => {refExpr}.Get<{t.Cs}>({self}); set => {refExpr}.Set({self}, value); }}\n");
                break;
            case Kind.String:
                Doc();
                o.Append($"{indent}public {st}string {name} {{ get => {refExpr}.GetString({self}); set => {refExpr}.SetString({self}, value); }}\n");
                break;
            case Kind.Wrapper:
                Doc();
                o.Append($"{indent}public {st}{t.Cs} {name} {{ get => new({refExpr}.GetObject({self})); set => {refExpr}.SetObject({self}, value.Ptr); }}\n");
                break;
            case Kind.Object:
                Doc();
                o.Append($"{indent}public {st}nint {name} {{ get => {refExpr}.GetObject({self}); set => {refExpr}.SetObject({self}, value); }}\n");
                break;
            default:
                // A struct without a mirror or an unknown type: only the field itself.
                o.Append($"{indent}/// <summary>{Names.Xml(doc)} (no C# mirror for this type: use the field reference).</summary>\n");
                o.Append($"{indent}public static global::Jibbers.Sdk.Interop.Il2CppField {name}_Field => {refExpr}.Field;\n");
                break;
        }
    }

    /// <summary>A method wrapper. Returns the C# signature key used for overload uniqueness.</summary>
    void Method(StringBuilder o, string indent, string name, string refExpr, MethodInfo mi, bool friendly, string doc, string selfType)
    {
        var ps = mi.Params.Select(p => m.Type(p, friendly)).ToList();
        var ret = m.Type(mi.Return, friendly);
        var args = new List<string>();
        var prep = new StringBuilder();
        var ptrs = new List<string>();
        for (var i = 0; i < ps.Count; i++)
        {
            var a = Names.Ident(mi.ParamName(i));
            switch (ps[i].Kind)
            {
                case Kind.Value:
                    args.Add($"{ps[i].Cs} {a}");
                    prep.Append($"{indent}    var p{i} = {a};\n");
                    ptrs.Add($"(nint)(&p{i})");
                    break;
                case Kind.String:
                    args.Add($"string? {a}");
                    ptrs.Add($"{a} is null ? 0 : global::Jibbers.Sdk.Interop.Il2Cpp.String({a})");
                    break;
                case Kind.Wrapper:
                    args.Add($"{ps[i].Cs} {a}");
                    ptrs.Add($"{a}.Ptr");
                    break;
                default:
                    args.Add($"nint {a}");
                    ptrs.Add(a);
                    break;
            }
        }
        var isCtor = mi.Name == ".ctor";
        var self = mi.Static || isCtor ? "0" : "Ptr";
        var call = isCtor ? $"{refExpr}.Invoke(__o{(ptrs.Count > 0 ? ", " : "")}{string.Join(", ", ptrs)})" : $"{refExpr}.Invoke({self}{(ptrs.Count > 0 ? ", " : "")}{string.Join(", ", ptrs)})";
        var paramDocs = string.Join("", mi.Params.Select((p, i) => $"{indent}/// <param name=\"{Names.Ident(mi.ParamName(i)).TrimStart('@')}\"><c>{Names.Xml(p)}</c>{(ps[i].Kind is Kind.Pointer or Kind.Unknown ? ": pointer to the value (structs, byrefs) or the object" : "")}</param>\n"));
        o.Append($"{indent}/// <summary>{Names.Xml(doc)}</summary>\n{paramDocs}");
        if (isCtor)
        {
            o.Append($"{indent}public static {selfType} {name}({string.Join(", ", args)})\n{indent}{{\n{prep}{indent}    var __o = Class.Class.New();\n{indent}    {call};\n{indent}    return new(__o);\n{indent}}}\n");
            return;
        }
        var st = mi.Static ? "static " : "";
        var (rt, body) = ret.Kind switch
        {
            Kind.Void => ("void", $"{call};"),
            Kind.Value => (ret.Cs, $"return {refExpr}.Invoke<{ret.Cs}>({self}{(ptrs.Count > 0 ? ", " : "")}{string.Join(", ", ptrs)});"),
            Kind.String => ("string", $"return global::Jibbers.Sdk.Interop.Il2Cpp.ReadString({call});"),
            Kind.Wrapper => (ret.Cs, $"return new({call});"),
            _ => ("nint", $"return {call};"),
        };
        o.Append($"{indent}public {st}{rt} {name}({string.Join(", ", args)})\n{indent}{{\n{prep}{indent}    {body}\n{indent}}}\n");
    }

    static string SignatureKey(Model m, MethodInfo mi, bool friendly) => "(" + string.Join(",", mi.Params.Select(p => m.Type(p, friendly).Cs)) + ")";

    // ---------------------------------------------------------------------------------------------
    // Friendly bindings.

    string Friendly()
    {
        var o = new StringBuilder(Header("Friendly game bindings: stable names for the game's classes and events (catalogue symbols)."));
        foreach (var ns in m.Friendly.GroupBy(f => f.Namespace))
        {
            o.Append($"\nnamespace {ns.Key}\n{{\n");
            foreach (var f in ns)
            {
                if (f.IsEvent)
                {
                    FriendlyEvent(o, f);
                }
                else if (f.Info.ValueType)
                {
                    FriendlyStatics(o, f);
                }
                else
                {
                    FriendlyClass(o, f);
                }
            }
            o.Append("}\n");
        }
        return o.ToString();
    }

    static string RealDoc(FriendlyType f) =>
        $"{Names.Xml(f.Symbol.Summary)} Symbol <c>{f.Symbol.Id}</c>; <c>{Names.Xml(f.Info.FullName)}</c> on the build these bindings came from.";

    void FriendlyClass(StringBuilder o, FriendlyType f)
    {
        var i = "    ";
        var mem = new Members(f.Name);
        o.Append($"{i}/// <summary>{RealDoc(f)}</summary>\n");
        if (f.Symbol.Notes.Length > 0)
        {
            o.Append($"{i}/// <remarks>{Names.Xml(f.Symbol.Notes)}</remarks>\n");
        }
        o.Append($"{i}public readonly unsafe partial struct {f.Name} : global::Jibbers.Sdk.IGameObject\n{i}{{\n");
        var b = i + "    ";
        o.Append($"{b}/// <summary>The symbol's class.</summary>\n{b}public static readonly {Sym}.ClassRef Class = new(\"{f.Symbol.Id}\");\n");
        o.Append($"{b}/// <summary>The object pointer.</summary>\n{b}public nint Ptr {{ get; }}\n");
        o.Append($"{b}/// <summary>Wraps an object pointer (no check: see <see cref=\"Cast\"/>).</summary>\n{b}public {f.Name}(nint ptr) {{ Ptr = ptr; }}\n");
        o.Append($"{b}/// <summary>Whether the pointer is null.</summary>\n{b}public bool IsNull => Ptr == 0;\n");
        o.Append($"{b}/// <summary>The object pointer, for any API taking one (<c>Unity.Call(x, ...)</c>).</summary>\n{b}public static implicit operator nint({f.Name} o) => o.Ptr;\n");
        o.Append($"{b}/// <summary>Wraps <paramref name=\"p\"/> if it is an instance of this class, else null.</summary>\n{b}public static {f.Name}? Cast(nint p) => Class.IsInstance(p) ? new {f.Name}(p) : null;\n");
        foreach (var n in new[] { "Class", "Ptr", "IsNull", "Cast", "get_Ptr", "get_IsNull", "op_Implicit" })
        {
            mem.Take(n);
        }
        if (m.IsUnityObject(f.Info))
        {
            o.Append($"{b}/// <summary>Every live (active) instance. Main thread.</summary>\n{b}public static {f.Name}[] All() => global::System.Linq.Enumerable.ToArray(global::System.Linq.Enumerable.Select(global::Jibbers.Sdk.Unity.FindObjects(Class.Class), p => new {f.Name}(p)));\n");
            o.Append($"{b}/// <summary>The first live instance, or null. Main thread.</summary>\n{b}public static {f.Name}? First() {{ var a = global::Jibbers.Sdk.Unity.FindObjects(Class.Class); return a.Length > 0 ? new {f.Name}(a[0]) : null; }}\n");
            mem.Take("All");
            mem.Take("First");
        }
        var raw = m.RawClasses.FirstOrDefault(r => r.Info.FullName == f.Info.FullName && r.Info.Image == f.Info.Image);
        if (raw is not null)
        {
            o.Append($"{b}/// <summary>The same object through the raw binding (every real member).</summary>\n{b}public {raw.Global} Raw => new(Ptr);\n");
            mem.Take("Raw");
        }
        var n2 = 0;
        foreach (var (mname, member) in f.Resolved.Members)
        {
            var path = $"{f.Symbol.Id}.{mname}";
            var decl = m.Snap.Classes[member.Class];
            if (member.IsField)
            {
                var fi = decl.Fields[member.Index];
                var refName = $"__f{n2++}";
                o.Append($"{b}static readonly {Sym}.FieldRef {refName} = new(\"{path}\");\n");
                Field(o, b, mem.Take(Names.Pascal(mname)), refName, m.Type(fi.Type, true), fi.Static, $"Field {mname} (`{fi.Name}: {fi.Type}`).");
            }
            else
            {
                var mi = decl.Methods[member.Index];
                var refName = $"__m{n2++}";
                var pub = Names.Pascal(mname);
                o.Append($"{b}static readonly {Sym}.MethodRef {refName} = new(\"{path}\");\n");
                o.Append($"{b}/// <summary>The method reference of {pub}: pre-hook it (<c>.Before</c>) or detour it (<c>.Detour</c>).</summary>\n{b}public static {Sym}.MethodRef {mem.Take(pub + "Method")} => {refName};\n");
                Method(o, b, mem.Take(pub, SignatureKey(m, mi, true)), refName, mi, true, $"Calls {mname} (`{mi.Name}({string.Join(", ", mi.Params)}) -> {mi.Return}`){(mi.Static ? ", static" : "")}.", f.Name);
            }
        }
        o.Append($"{i}}}\n\n");
    }

    void FriendlyEvent(StringBuilder o, FriendlyType f)
    {
        var i = "    ";
        var mem = new Members(f.Name);
        o.Append($"{i}/// <summary>Event: {RealDoc(f)} Subscribe with <see cref=\"Subscribe\"/>.</summary>\n");
        o.Append($"{i}public readonly unsafe struct {f.Name}\n{i}{{\n");
        var b = i + "    ";
        o.Append($"{b}/// <summary>The event symbol id.</summary>\n{b}public const string Id = \"{f.Symbol.Id}\";\n");
        o.Append($"{b}/// <summary>The received event (valid only during the callback).</summary>\n{b}public global::Jibbers.Sdk.GameEvent Event {{ get; }}\n");
        o.Append($"{b}/// <summary>Wraps a received event.</summary>\n{b}public {f.Name}(global::Jibbers.Sdk.GameEvent e) {{ Event = e; }}\n");
        o.Append($"{b}/// <summary>Calls <paramref name=\"callback\"/> on the main thread every time the game raises this event. Removed when your mod unloads.</summary>\n");
        o.Append($"{b}public static global::Jibbers.Sdk.Subscription Subscribe(global::System.Action<{f.Name}> callback) => global::Jibbers.Sdk.Events.Subscribe(Id, e => callback(new {f.Name}(e)));\n");
        o.Append($"{b}/// <summary>Sends this event to every listener (game and mods) with zeroed data. Main thread.</summary>\n{b}public static int RaiseEmpty() => global::Jibbers.Sdk.Events.Raise(Id);\n");
        foreach (var n in new[] { "Id", "Event", "Subscribe", "RaiseEmpty" })
        {
            mem.Take(n);
        }
        var n2 = 0;
        foreach (var (mname, member) in f.Resolved.Members)
        {
            if (!member.IsField)
            {
                continue;
            }
            var fi = m.Snap.Classes[member.Class].Fields[member.Index];
            var t = m.Type(fi.Type, true);
            var refName = $"__f{n2++}";
            o.Append($"{b}static readonly {Sym}.FieldRef {refName} = new(\"{f.Symbol.Id}.{mname}\");\n");
            var name = mem.Take(Names.Pascal(mname));
            var doc = $"Field {mname} (`{fi.Name}: {fi.Type}`).";
            switch (t.Kind)
            {
                case Kind.Value:
                    o.Append($"{b}/// <summary>{Names.Xml(doc)}</summary>\n{b}public {t.Cs} {name} => Event.Get<{t.Cs}>({refName});\n");
                    break;
                case Kind.String:
                    o.Append($"{b}/// <summary>{Names.Xml(doc)}</summary>\n{b}public string {name} => Event.GetString({refName});\n");
                    break;
                case Kind.Wrapper:
                    o.Append($"{b}/// <summary>{Names.Xml(doc)}</summary>\n{b}public {t.Cs} {name} => new(Event.GetObject({refName}));\n");
                    break;
                case Kind.Object:
                    o.Append($"{b}/// <summary>{Names.Xml(doc)}</summary>\n{b}public nint {name} => Event.GetObject({refName});\n");
                    break;
                default:
                    o.Append($"{b}/// <summary>{Names.Xml(doc)} Pointer to the field's data.</summary>\n{b}public nint {name} => Event.Data + {refName}.StructOffset;\n");
                    break;
            }
        }
        o.Append($"{i}}}\n\n");
    }

    void FriendlyStatics(StringBuilder o, FriendlyType f)
    {
        var i = "    ";
        var mem = new Members(f.Name);
        o.Append($"{i}/// <summary>{RealDoc(f)}</summary>\n{i}public static unsafe class {f.Name}\n{i}{{\n");
        var b = i + "    ";
        o.Append($"{b}/// <summary>The symbol's class.</summary>\n{b}public static readonly {Sym}.ClassRef Class = new(\"{f.Symbol.Id}\");\n");
        mem.Take("Class");
        var n2 = 0;
        foreach (var (mname, member) in f.Resolved.Members)
        {
            if (!member.IsField)
            {
                continue;
            }
            var fi = m.Snap.Classes[member.Class].Fields[member.Index];
            var refName = $"__f{n2++}";
            o.Append($"{b}static readonly {Sym}.FieldRef {refName} = new(\"{f.Symbol.Id}.{mname}\");\n");
            var t = fi.Type == f.Info.FullName ? new CsType(Kind.Value, "int") : m.Type(fi.Type, true);
            if (fi.Static && t.Kind == Kind.Value)
            {
                o.Append($"{b}/// <summary>Value of {mname} (`{Names.Xml(fi.Name)}`).</summary>\n{b}public static {t.Cs} {mem.Take(Names.Pascal(mname))} => {refName}.Get<{t.Cs}>(0);\n");
            }
        }
        o.Append($"{i}}}\n\n");
    }

    // ---------------------------------------------------------------------------------------------
    // Raw bindings.

    string Raw(string image, List<RawType> classes)
    {
        var o = new StringBuilder(Header($"Raw bindings for every class of {image}: real (often obfuscated) names. Prefer Jibbers.Sdk.Game.* where a symbol exists: those names survive game updates."));
        foreach (var ns in classes.GroupBy(c => c.Namespace))
        {
            o.Append($"\nnamespace {ns.Key}\n{{\n");
            foreach (var c in ns)
            {
                RawClass(o, c);
            }
            o.Append("}\n");
        }
        return o.ToString();
    }

    void RawClass(StringBuilder o, RawType c)
    {
        var i = "    ";
        var k = c.Info;
        var mem = new Members(c.Name);
        o.Append($"{i}/// <summary>Raw binding of <c>{Names.Xml(k.FullName)}</c> ({k.Image}{(k.Parent.Length > 0 ? ", derives from " + Names.Xml(k.Parent) : "")}).</summary>\n");
        o.Append($"{i}public readonly unsafe partial struct {c.Name} : global::Jibbers.Sdk.IGameObject\n{i}{{\n");
        var b = i + "    ";
        o.Append($"{b}/// <summary>The class.</summary>\n{b}public static readonly {Sym}.RawClassRef Class = new(\"{k.Image}\", \"{k.Namespace}\", \"{c.RefName}\");\n");
        o.Append($"{b}/// <summary>The object pointer.</summary>\n{b}public nint Ptr {{ get; }}\n");
        o.Append($"{b}/// <summary>Wraps an object pointer.</summary>\n{b}public {c.Name}(nint ptr) {{ Ptr = ptr; }}\n");
        o.Append($"{b}/// <summary>Whether the pointer is null.</summary>\n{b}public bool IsNull => Ptr == 0;\n");
        o.Append($"{b}/// <summary>The object pointer, for any API taking one (<c>Unity.Call(x, ...)</c>).</summary>\n{b}public static implicit operator nint({c.Name} o) => o.Ptr;\n");
        foreach (var n in new[] { "Class", "Ptr", "IsNull", "get_Ptr", "get_IsNull", "op_Implicit" })
        {
            mem.Take(n);
        }
        if (m.IsUnityObject(k))
        {
            o.Append($"{b}/// <summary>Every live instance. Main thread.</summary>\n{b}public static {c.Name}[] Live() => global::System.Linq.Enumerable.ToArray(global::System.Linq.Enumerable.Select(Class.Live(), p => new {c.Name}(p)));\n");
            mem.Take("Live");
        }
        var n2 = 0;
        foreach (var f in k.Fields)
        {
            var refName = $"__f{n2}";
            o.Append($"{b}static {Sym}.RawFieldRef? {refName}_;\n{b}static {Sym}.RawFieldRef {refName} => {refName}_ ??= new(Class, \"{f.Name}\");\n");
            n2++;
            Field(o, b, mem.Take(Names.Ident(f.Name)), refName, m.Type(f.Type, false), f.Static, $"Field `{f.Name}: {f.Type}`{(f.Static ? " (static)" : "")}.");
        }
        foreach (var mi in k.Methods)
        {
            if (mi.Name is ".cctor" || mi.Name.Contains('<') || mi.Name.Contains('|'))
            {
                continue;
            }
            var refName = $"__m{n2}";
            var types = string.Join(", ", mi.Params.Select(p => "\"" + p.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\""));
            o.Append($"{b}static {Sym}.RawMethodRef? {refName}_;\n{b}static {Sym}.RawMethodRef {refName} => {refName}_ ??= new(Class, \"{mi.Name}\"{(types.Length > 0 ? ", " + types : "")});\n");
            n2++;
            var baseName = mi.Name == ".ctor" ? "New" : Names.Ident(mi.Name);
            var name = mem.Take(baseName, SignatureKey(m, mi, false));
            o.Append($"{b}/// <summary>The method reference of {name}: detour or pre-hook it.</summary>\n{b}public static {Sym}.RawMethodRef {mem.Take(name + "_Method")} => {refName};\n");
            Method(o, b, name, refName, mi, false, $"`{mi.Name}({string.Join(", ", mi.Params)}) -> {mi.Return}`{(mi.Static ? " (static)" : "")}.", c.Name);
        }
        o.Append($"{i}}}\n\n");
    }
}
