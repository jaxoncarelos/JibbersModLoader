//! Game-build gate: decides, once and before anything is hooked, whether the mods may run on this
//! build of the game.
//!
//! The mods hook obfuscated game code that can change in any update; a hook on the wrong code
//! crashes natively inside Unity, beyond the reach of any `catch_unwind`. So `init_game` asks
//! [`gate`] first. On a build that is not in the compatibility list nothing is hooked and no plugin
//! is loaded, except the SDK runtime (see `core::attach_runtime_only`), which hooks nothing and
//! whose updater can fetch a newer list. Logic lives in the shared `gamebuild` module; this file
//! adds the loader's compiled-in list, the log line and the notice file.

use crate::gamebuild::{self, Fingerprint, Verdict};
use crate::{game_dir, log};
use std::path::{Path, PathBuf};
use std::sync::OnceLock;

/// The list this loader was built with (`sdk/compat/compat.json`, generated by
/// `sdk-publish validate-build`). A newer one installed by the SDK updater supersedes it.
const EMBEDDED_LIST: &str = include_str!("../../../sdk/compat/compat.json");

/// Written beside the plugins while mods are off, so a player who looks can see why.
pub const NOTICE_FILE: &str = "MODS-DISABLED.txt";

static VERDICT: OnceLock<Verdict> = OnceLock::new();

pub fn mods_dir() -> PathBuf {
    game_dir().join("JibbersMods")
}

/// The verdict for the running game. Computed on first use; logs its one line and writes or
/// removes the notice file then. Never re-evaluated, so a mismatch is logged exactly once.
pub fn gate() -> &'static Verdict {
    VERDICT.get_or_init(|| {
        let mods = mods_dir();
        let force = gamebuild::force_requested(std::env::var(gamebuild::FORCE_ENV).ok().as_deref());
        let (verdict, notes) = decide(&gamebuild::fingerprint_loaded(), EMBEDDED_LIST, &mods, force);
        for n in notes {
            log::info(format!("compat: {n}"));
        }
        log::info(verdict.message());
        sync_notice(&mods, &verdict);
        verdict
    })
}

/// True once [`gate`] has refused the game build.
pub fn blocked() -> bool {
    VERDICT.get().is_some_and(|v| !v.allows_mods())
}

/// Pure decision: the fingerprint against the built-in list (or a newer installed one).
pub fn decide(fp: &Result<Fingerprint, String>, embedded: &str, mods_dir: &Path, force: bool) -> (Verdict, Vec<String>) {
    let (list, notes) = gamebuild::resolve_list(embedded, mods_dir);
    (gamebuild::evaluate(fp, &list, force), notes)
}

/// Creates the notice file for a refused build and removes a stale one otherwise.
pub fn sync_notice(mods_dir: &Path, verdict: &Verdict) {
    let path = mods_dir.join(NOTICE_FILE);
    if verdict.allows_mods() {
        let _ = std::fs::remove_file(&path);
        return;
    }
    let text = format!(
        "Jibbers mods are switched off for this game build.\r\n\r\n{}\r\n\r\nThe mods hook parts of the game that can change when it updates, and hooking the wrong code can crash the game. \
         Nothing is wrong with your install. When the mods have been checked against this build, the SDK updater downloads the new list on its own (restart the game once afterwards); \
         otherwise ask the mod author for an update.\r\n",
        verdict.message()
    );
    let _ = std::fs::create_dir_all(mods_dir);
    let _ = std::fs::write(path, text);
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::gamebuild::{CompatList, KnownBuild};

    fn fp(size: u64, hash: u64) -> Fingerprint {
        Fingerprint { assembly_size: size, pe_timestamp: 1, header_hash: hash, unity: "6000.3.12f1 (fca03ac9b0d5)".into() }
    }

    fn list_text(version: &str, builds: &[(u64, u64)]) -> String {
        let l = CompatList {
            sdk_version: version.into(),
            generated: String::new(),
            builds: builds.iter().map(|(s, h)| KnownBuild { label: format!("build {s}"), fingerprint: fp(*s, *h), validated: String::new(), note: String::new() }).collect(),
        };
        l.to_json().to_string()
    }

    fn temp(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("jibbers-compat-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("sdk")).unwrap();
        dir
    }

    #[test]
    fn built_in_list_is_valid_and_names_a_build() {
        let list = CompatList::parse(EMBEDDED_LIST).expect("sdk/compat/compat.json must parse");
        assert!(!list.builds.is_empty(), "the loader needs at least one validated build");
        assert!(list.builds.iter().all(|b| b.fingerprint.assembly_size > 0 && !b.fingerprint.unity.is_empty()));
    }

    #[test]
    fn the_tested_build_loads_and_another_build_is_refused() {
        let dir = temp("decide");
        let embedded = list_text("0.1.0", &[(111_196_160, 0xAB)]);
        let (ok, _) = decide(&Ok(fp(111_196_160, 0xAB)), &embedded, &dir, false);
        assert!(ok.allows_mods());
        // the player's build from the crash report: bigger GameAssembly, same Unity
        let (bad, _) = decide(&Ok(fp(114_143_232, 0xCD)), &embedded, &dir, false);
        assert!(!bad.allows_mods());
        assert!(bad.message().contains("114143232 bytes"));
        assert!(bad.message().contains("not validated; mods disabled (loader built for build 111196160)"));
    }

    #[test]
    fn force_lets_a_developer_load_on_an_unvalidated_build() {
        let dir = temp("force");
        let embedded = list_text("0.1.0", &[(111_196_160, 0xAB)]);
        let (v, _) = decide(&Ok(fp(114_143_232, 0xCD)), &embedded, &dir, true);
        assert!(v.allows_mods());
        assert!(v.message().contains("JIBBERS_HOTLOAD_FORCE"));
    }

    #[test]
    fn an_sdk_update_can_validate_the_new_build_without_a_new_loader() {
        let dir = temp("update");
        let embedded = list_text("0.1.0", &[(111_196_160, 0xAB)]);
        let newer = list_text("0.2.0", &[(111_196_160, 0xAB), (114_143_232, 0xCD)]);
        std::fs::write(gamebuild::installed_list_path(&dir), newer).unwrap();
        let (v, notes) = decide(&Ok(fp(114_143_232, 0xCD)), &embedded, &dir, false);
        assert!(v.allows_mods() && notes.is_empty(), "{v:?} {notes:?}");
    }

    #[test]
    fn notice_file_follows_the_verdict() {
        let dir = temp("notice");
        let embedded = list_text("0.1.0", &[(111_196_160, 0xAB)]);
        let (bad, _) = decide(&Ok(fp(1, 2)), &embedded, &dir, false);
        sync_notice(&dir, &bad);
        let text = std::fs::read_to_string(dir.join(NOTICE_FILE)).unwrap();
        assert!(text.contains("not validated; mods disabled"));
        let (ok, _) = decide(&Ok(fp(111_196_160, 0xAB)), &embedded, &dir, false);
        sync_notice(&dir, &ok);
        assert!(!dir.join(NOTICE_FILE).exists(), "stale notice removed once the build is validated");
    }
}
